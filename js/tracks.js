// Hand-authored control-point polylines approximating real F1 circuits.
// These are stylized layouts (recognizable shape/character) tuned for FUN,
// DRIVEABLE arcade gameplay over real-world survey accuracy - see
// generateCircuit() in track.js for how they're consumed.
//
// Each entry is an array of {x, z} control points fed into the same
// THREE.CatmullRomCurve3(points, true) + .getSpacedPoints(cfg.trackRes) pipeline
// used by the procedural generator, so the same downstream mesh/physics/scenery
// code works unmodified for both real and procedural tracks.
//
// Two structural requirements drive every layout here, on top of the basic
// closed-loop / no-self-intersection / minimum-separation checks:
//
// 1. Minimum turn radius. generatePitLane() places the pit wall, garages and
//    grandstands by offsetting a fixed perpendicular distance from the LOCAL
//    tangent at each of the ~800 resampled track points, and isSpaceClear()
//    (also in track.js) explicitly excludes the first/last 75 samples from its
//    own overlap check (that zone IS the pit lane, so it can't reject its own
//    structures) - meaning nothing protects that stretch from the track's own
//    curvature. Sharp corners there previously caused pit-lane structures to fan
//    out at conflicting angles and clip into the track surface. Separately, this
//    arcade physics model (roadWidth 18, steering angle clamped, top speed
//    340kph) cannot cleanly drive a tight real-world hairpin at any reasonable
//    speed. Every corner in every track below was authored (via a turtle-style
//    straight+circular-arc builder, not freehand) to keep the local turn radius
//    comfortably above ~48 units everywhere on the resampled curve - real tight
//    corners (Monaco's hairpin, Singapore's 90-degree corners, Suzuka's esses,
//    Zandvoort's Tarzan, etc.) are deliberately widened into gentler sweeps. Fun,
//    driveable gameplay was prioritized over literal corner shape throughout.
//
// 2. Straight pit zone. Control-point index 0 in each array below is the
//    start/finish line, and generatePitLane()'s placement math assumes that
//    stretch of track is close to straight (it offsets structures from the local
//    tangent across a fixed +/-60-sample window). Roughly the first/last ~11% of
//    each lap's arc length either side of index 0 - with margin - is kept close
//    to dead straight for exactly this reason. That's proportionally a longer
//    pit straight than any real circuit has, which is an explicit, deliberate
//    trade of authenticity for a pit lane that never clips the track. Where a
//    track's real pit straight/start-finish corner didn't naturally support this,
//    the lap was re-authored around a straight run instead, so "index 0" no
//    longer necessarily corresponds to the same real-world corner it used to -
//    nothing else depends on which real corner the start line nominally matches.
//
// Every layout has been validated with a throwaway Node script (three.js +
// CatmullRomCurve3, replicating the exact production pipeline) that checks, for
// all 800 resampled points: (a) continuity - no jump between consecutive points
// over ~15 units; (b) no self-intersection between non-adjacent segments;
// (c) minimum separation between non-adjacent points over ~30 units (roadWidth is
// 18); (d) local turn radius (3-point circumscribed-circle estimate over an
// ~15-unit arc-length window) stays above ~48 units everywhere; (e) within +/-90
// samples of index 0 (wrapping), turn radius stays above ~400 units (near-
// straight, well clear of the pit-lane builder's +/-60/+/-75-sample zones). All
// 10 tracks pass all 5 checks. The script itself was not kept.

